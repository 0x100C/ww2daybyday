"""Finnish and Arctic fronts, June 1941 - April 1945.

Continuation War advance (sources: H. Seppala, Finnish official history
maps; Ziemke, "The German Northern Theater of Operations" 1959):
10-16 Jul 1941 Finns reach Lake Ladoga at Koirinoja; 16 Aug Sortavala;
21 Aug Kexholm; 29 Aug Viipuri; 31 Aug-2 Sep old border on the Isthmus;
5-7 Sep Olonets and the Svir; 1 Oct Petrozavodsk; 5-6 Dec
Medvezhyegorsk and Povenets. German Army of Norway: Litsa front from
29 Jun; Salla taken 8 Jul, Alakurtti Sep; Kestenga Nov 1941.
Static 1942 - May 1944. Soviet Vyborg-Petrozavodsk offensive: 10 Jun
1944 Isthmus, 20 Jun Viipuri, Tali-Ihantala to 9 Jul; 21 Jun Svir,
28 Jun Petrozavodsk; Finns back on the U-line by mid-July.
Armistice 19 Sep 1944: 1940 border, Petsamo ceded, Porkkala leased.
Lapland War: Germans withdraw to Norway (Rovaniemi 14 Oct, last
Finnish soil left 27 Apr 1945). Petsamo-Kirkenes operation 7-25 Oct 1944.
"""
from ctools import Front, blob, J
from core import world
import borders as B

CW = [(60.05, 27.0), (60.0, 22.0), (62.0, 19.0), (66.0, 23.0), (70.0, 22.0), (71.5, 28.0), (70.2, 31.0)]
CE = [(70.3, 33.0), (70.5, 45.0), (60.0, 45.0), (59.6, 32.0), (59.9, 30.6)]

BORDER_OUT = [(69.62, 31.40), (69.00, 28.80), (68.00, 28.70), (67.00, 28.80), (66.00, 29.50), (65.00, 29.70),
              (64.00, 29.80), (63.00, 31.00), (62.00, 30.80), (61.20, 29.60), (60.70, 27.90), (60.55, 27.70)]

ISTHMUS_OLD = [(60.42, 30.95), (60.33, 30.28), (60.23, 30.14), (60.16, 30.02), (60.13, 29.95)]
NORTH_1941 = [(69.62, 31.80), (69.50, 32.15), (69.42, 32.40), (69.20, 32.20), (68.80, 31.00), (68.20, 30.30),
              (67.60, 30.20)]
SALLA_DEC41 = [(67.20, 30.85), (66.95, 30.85), (66.70, 30.70), (66.40, 30.60), (66.05, 30.30)]
KESTENGA = [(66.00, 32.30), (65.85, 32.40), (65.70, 32.10), (65.40, 31.50)]
UKHTA = [(65.10, 31.10), (64.90, 31.40), (64.40, 31.80), (63.75, 32.70)]
MAASELKA = [(63.40, 33.80), (63.15, 34.35), (62.85, 34.82)]
SVIR = [(62.10, 35.40), (61.10, 35.60), (60.95, 35.00), (60.65, 34.60), (60.55, 34.00), (60.70, 33.40),
        (60.80, 33.00), (60.75, 32.70)]
NORTH_ALL = NORTH_1941 + SALLA_DEC41 + KESTENGA + UKHTA
STATIC_42 = NORTH_ALL + MAASELKA + SVIR + ISTHMUS_OLD


def build(tl):
    W = world()
    F = Front(tl, "finland", "FIN", "SOV", ["SOV"], ["FIN"], CW, CE, order=62, jitter_amp=3.0, jitter_seg=9.0, seed=61)
    F.e_active = False
    F.key("1941-06-25 06", BORDER_OUT, raw=True)
    F.key("1941-07-16 00", NORTH_1941[:4] + [(69.00, 30.80), (68.40, 30.10), (67.40, 30.10), (67.10, 29.95),
                                              (66.90, 30.10), (66.60, 30.00), (66.00, 29.90), (65.00, 29.80),
                                              (64.00, 30.00), (63.00, 31.20), (62.70, 32.20), (62.30, 32.60),
                                              (61.90, 32.20), (61.62, 31.55), (61.55, 31.15), (61.40, 30.80),
                                              (61.10, 30.20), (60.85, 29.60), (60.75, 28.70), (60.60, 27.95)])
    F.key("1941-08-01 00", NORTH_1941[:4] + [(69.00, 30.90), (68.40, 30.20), (67.40, 30.20), (67.10, 30.20),
                                              (66.90, 30.30), (66.60, 30.20), (66.00, 30.20), (65.70, 31.20),
                                              (65.50, 30.80), (65.00, 30.20), (64.00, 30.20), (63.00, 31.70),
                                              (62.70, 32.80), (62.30, 33.20), (61.90, 33.00), (61.60, 32.40),
                                              (61.55, 31.40), (61.62, 31.10), (61.55, 30.85), (61.30, 30.40),
                                              (61.05, 29.95), (60.85, 29.30), (60.70, 28.40), (60.60, 27.95)])
    F.key("1941-08-22 00", NORTH_1941[:4] + [(69.00, 30.95), (68.40, 30.25), (67.40, 30.30), (67.10, 30.60),
                                              (66.90, 30.65), (66.60, 30.50), (66.00, 30.40), (65.75, 31.60),
                                              (65.50, 31.00), (65.00, 30.50), (64.20, 31.20), (63.40, 32.30),
                                              (62.80, 33.30), (62.30, 33.60), (61.90, 33.50), (61.55, 33.00),
                                              (61.30, 32.20), (61.10, 31.60), (61.00, 31.00), (60.95, 30.30),
                                              (60.85, 29.80), (60.78, 29.30), (60.72, 28.80), (60.60, 28.30)])
    F.key("1941-09-08 00", NORTH_1941 + SALLA_DEC41[:3] + [(66.40, 30.40), (66.00, 30.50), (65.80, 31.80),
                                                            (65.55, 31.40), (65.10, 31.00), (64.60, 31.40),
                                                            (63.90, 32.50), (63.20, 33.30), (62.60, 34.00),
                                                            (62.00, 34.30), (61.40, 34.00), (61.05, 33.80),
                                                            (60.90, 33.40), (60.80, 33.00), (60.75, 32.70)]
          + ISTHMUS_OLD)
    F.key("1941-10-02 00", NORTH_1941 + SALLA_DEC41 + [(65.85, 32.20), (65.60, 31.80), (65.30, 31.30), (65.10, 31.10),
                                                        (64.70, 31.50), (64.00, 32.40), (63.40, 33.60), (62.95, 34.20),
                                                        (62.30, 34.90), (61.80, 35.30), (61.10, 35.60), (60.95, 35.00),
                                                        (60.65, 34.60), (60.55, 34.00), (60.70, 33.40), (60.80, 33.00),
                                                        (60.75, 32.70)] + ISTHMUS_OLD)
    F.key("1941-12-07 00", STATIC_42)
    # Finland re-annexes the territory ceded in 1940 (parliament, 6 Dec 1941)
    ceded = lambda: (W.poly(B.FIN_KARELIA_1920) | W.poly(B.FIN_SALLA_1920) | W.polys(*B.FIN_GULF_ISLANDS)) & W.unit("RUS")  # noqa: E731
    tl.political("1941-12-06", ceded, "FIN", where=["SOV"], dur=1.0, label="Finland re-annexes the 1940 territory")
    F.key("1944-06-09 00", STATIC_42)
    F.e_active = True
    F.key("1944-06-14 00", NORTH_ALL + MAASELKA + SVIR + [(60.42, 30.95), (60.45, 30.40), (60.50, 29.90), (60.40, 29.40),
                                              (60.25, 28.95), (60.20, 28.70)])
    F.key("1944-06-21 00", NORTH_ALL + MAASELKA + [(62.10, 35.40), (61.30, 35.20), (61.10, 34.20),
                                               (60.95, 33.40), (60.80, 32.90), (60.75, 32.70), (60.42, 30.95),
                                               (60.50, 30.40), (60.65, 29.90), (60.72, 29.30), (60.73, 28.85),
                                               (60.65, 28.60), (60.55, 28.35)])
    F.key("1944-07-10 00", NORTH_ALL + [(63.20, 32.60), (62.60, 32.10), (62.10, 31.80),
                                               (61.70, 31.80), (61.40, 32.10), (61.20, 32.30), (60.95, 30.95),
                                               (60.85, 30.20), (60.80, 29.60), (60.78, 29.10), (60.75, 28.85),
                                               (60.65, 28.60), (60.55, 28.35)])
    F.key("1944-08-15 00", NORTH_ALL + [(63.20, 32.30), (62.70, 31.70), (62.30, 31.30),
                                               (61.90, 31.10), (61.55, 31.30), (61.25, 31.60), (60.95, 30.95),
                                               (60.85, 30.20), (60.80, 29.60), (60.78, 29.10), (60.75, 28.85),
                                               (60.65, 28.60), (60.55, 28.35)])
    rus = W.unit("RUS")
    ceded44 = lambda: ((W.poly(B.FIN_KARELIA_1920) | W.poly(B.FIN_SALLA_1920) |  # noqa: E731
                        W.polys(*B.FIN_GULF_ISLANDS) | W.poly(B.FIN_PETSAMO)) & rus)
    tl.political("1944-09-21", ceded44, "SOV", where=["FIN"], dur=2.0, label="Moscow armistice")
    F.end("1944-09-25 12")
    # Porkkala naval base leased to the USSR
    pk = tl.layer("porkkala", "SOV", within=["FIN"], order=63)
    pk.key("1944-09-26 12", blob([(60.18, 24.15), (60.18, 24.60), (59.98, 24.60), (59.98, 24.15)], amp=0.8, seed=62))

    # Germans in northern Finland: Lapland War
    lap = tl.layer("lapland", "GER", within=["FIN"], order=64)
    lap.key("1944-09-15 00", J([(66.10, 23.6), (66.00, 25.5), (65.80, 27.5), (65.40, 29.0), (65.0, 29.8)], amp=4, seg=10)
            + [(69.0, 31.5), (70.5, 28.0), (69.5, 20.0), (67.5, 20.0)])
    lap.key("1944-10-15 00", J([(67.20, 23.3), (66.70, 25.0), (66.50, 26.5), (66.70, 28.5), (66.90, 29.8)], amp=4, seg=10)
            + [(69.0, 31.5), (70.5, 28.0), (69.5, 20.0), (67.5, 20.0)])
    lap.key("1944-11-10 00", J([(68.50, 22.5), (68.30, 24.5), (68.60, 26.5), (69.20, 28.5)], amp=4, seg=10)
            + [(70.5, 28.0), (69.5, 20.0)])
    lap.key("1944-11-30 00", J([(69.05, 20.5), (68.80, 21.5), (68.60, 22.5)], amp=3, seg=8) + [(68.4, 20.0), (69.5, 19.0)])
    lap.end("1945-04-27 12")
    kirk = tl.layer("finnmark-1944", "SOV", within=["NOR"], order=63)
    kirk.key("1944-10-25 12", blob([(70.00, 28.40), (69.95, 30.90), (69.50, 31.20), (69.05, 29.40), (69.40, 28.70)], seed=63))
    kirk.key("1944-11-08 12", blob([(70.40, 27.90), (70.10, 31.00), (69.50, 31.20), (69.05, 29.10), (69.50, 28.00)], seed=64))

    for d, t in [("1941-06-25", "Finland goes to war alongside Germany"),
                 ("1941-08-29", "Finnish troops retake Viipuri"),
                 ("1941-10-01", "Finnish troops take Petrozavodsk"),
                 ("1944-06-10", "The Red Army attacks on the Karelian Isthmus"),
                 ("1944-06-20", "Viipuri falls to the Red Army"),
                 ("1944-09-19", "Finland signs an armistice with the Soviet Union"),
                 ("1944-10-25", "The Red Army liberates Kirkenes")]:
        tl.caption(d, t)
